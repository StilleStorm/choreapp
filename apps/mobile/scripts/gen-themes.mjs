// Generates the 25 child themes from packages/seed/themes.json (tokens taken
// from the design mockups):
//   src/lib/themes/themes.css   [data-theme] blocks with CSS custom properties
//   src/lib/themes/themes.ts    list for the theme picker
//   static/fonts/**             Google Fonts (OFL) bundled into the APK, latin + latin-ext
// Usage: node scripts/gen-themes.mjs [--skip-fonts]
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const themes = JSON.parse(readFileSync(join(root, '../../packages/seed/themes.json'), 'utf8'));
const skipFonts = process.argv.includes('--skip-fonts');

// Accessibility fixes over the mockup values (contrast notes from extraction):
// colours used as text on light cards inside dark themes, and fills that
// were just below WCAG AA for white text.
// Also for the adults' screens (lists, forms, sheets): --surface-2 fills plain
// buttons, inputs' neighbours and badges behind --text, so it must stay light
// where cards are light (the mockups' dark strip colour keeps the icon tiles),
// and --accent is used as text for links and badges.
const FIXES = {
  manga: { theme: { surface2: '#EDEDED', iconBg: '#111111' } },
  guild: { card: { muted: '#5A3D22', points: '#8A5A12', warning: '#7A4B12', success: '#2F5A2B' } },
  lanterns: {
    card: { muted: '#4A5676', points: '#9C4A12', warning: '#8A5A00', success: '#2F6A3B', 'surface-2': '#F0E2C4' },
    theme: { heroBg: '#C62F3B' },
  },
  detective: {
    card: {
      muted: '#3F3A2A',
      points: '#7A5C00',
      warning: '#7A5C00',
      success: '#2F5A2B',
      'surface-2': '#DDCDA4',
      accent: '#18202E',
      'accent-text': '#FFD43B',
      'accent-soft': '#DDCDA4',
    },
  },
  retro90: { theme: { success: '#6FE0E8' } },
  sport: { theme: { points: '#C2410C', accent: '#C2410C', accentText: '#FFFFFF', surface2: '#E6EAF2', iconBg: '#0B152B' } },
  monsters: { theme: { btnBg: '#237A46', accent: '#237A46' } },
  ducks: { theme: { accent: '#A64F00', accentText: '#FFFFFF' } },
  comic: { theme: { btnBg: '#C81E15', accent: '#C81E15', surface2: '#E3E9FA', iconBg: '#1A3FB5' } },
};

const fontFamilies = new Map(); // family -> Set of weight specs
for (const t of themes) {
  for (const spec of t.googleFonts) {
    const [family, weights = '400'] = spec.split(':');
    const set = fontFamilies.get(family) ?? new Set();
    for (const w of weights.split(',')) set.add(w.trim());
    fontFamilies.set(family, set);
  }
}

// ---------------------------------------------------------------------------
// Fonts
// ---------------------------------------------------------------------------
const fontsDir = join(root, 'static/fonts');
if (!skipFonts) {
  mkdirSync(fontsDir, { recursive: true });
  const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';
  const faces = [];
  for (const [family, weights] of fontFamilies) {
    const upright = [...weights].filter((w) => !w.endsWith('i')).sort();
    const italic = [...weights].filter((w) => w.endsWith('i')).map((w) => w.slice(0, -1)).sort();
    const axis = italic.length
      ? `ital,wght@${[...upright.map((w) => `0,${w}`), ...italic.map((w) => `1,${w}`)].join(';')}`
      : `wght@${upright.join(';')}`;
    const url = `https://fonts.googleapis.com/css2?family=${encodeURIComponent(family).replace(/%20/g, '+')}:${axis}&display=swap`;
    const res = await fetch(url, { headers: { 'User-Agent': UA } });
    if (!res.ok) throw new Error(`${family}: ${res.status} ${url}`);
    const css = await res.text();
    // Blocks look like: /* latin-ext */ @font-face { ... }
    for (const m of css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*{[^}]+})/g)) {
      const subset = m[1];
      if (subset !== 'latin' && subset !== 'latin-ext') continue;
      let block = m[2];
      const src = /url\((https:[^)]+\.woff2)\)/.exec(block)?.[1];
      if (!src) continue;
      const style = /font-style:\s*(\w+)/.exec(block)?.[1] ?? 'normal';
      const weight = /font-weight:\s*([\d ]+)/.exec(block)?.[1]?.trim().replace(/\s+/g, '-') ?? '400';
      const file = `${family.replace(/\s+/g, '')}-${weight}${style === 'italic' ? 'i' : ''}-${subset}.woff2`;
      const path = join(fontsDir, file);
      if (!existsSync(path)) {
        const f = await fetch(src);
        if (!f.ok) throw new Error(`${file}: ${f.status}`);
        writeFileSync(path, Buffer.from(await f.arrayBuffer()));
      }
      block = block.replace(/src:[^;]+;/, `src: url('/fonts/${file}') format('woff2');`);
      faces.push(block);
    }
  }
  writeFileSync(join(fontsDir, 'fonts.css'), `/* Generated by scripts/gen-themes.mjs: Google Fonts, SIL Open Font License 1.1 */\n${faces.join('\n')}\n`);
  writeFileSync(
    join(fontsDir, 'LICENSE.txt'),
    `Fonts bundled from Google Fonts (https://fonts.google.com), all licensed under the SIL Open Font License 1.1\n(https://openfontlicense.org). Families:\n${[...fontFamilies.keys()].sort().join('\n')}\n`,
  );
  console.log(`fonts: ${faces.length} faces from ${fontFamilies.size} families`);
}

// ---------------------------------------------------------------------------
// Theme CSS
// ---------------------------------------------------------------------------
// Light tints keep the coloured badge and button text near WCAG AA.
// Precomputed (same result as `color-mix(in srgb, c pct%, surface)`) because
// color-mix needs Chrome 111 and children's phones can have an older WebView.
const hex = (c) => {
  if (!/^#[0-9a-f]{6}$/i.test(c)) throw new Error(`soft(): expected #rrggbb, got ${c}`);
  return [1, 3, 5].map((i) => parseInt(c.slice(i, i + 2), 16));
};
const soft = (c, pct, surface) => {
  const a = hex(c);
  const b = hex(surface);
  return `#${a.map((v, i) => Math.round((v * pct + b[i] * (100 - pct)) / 100).toString(16).padStart(2, '0')).join('').toUpperCase()}`;
};
const blocks = [];
const list = [];
for (const raw of themes) {
  const fix = FIXES[raw.id] ?? {};
  const t = { ...raw, ...(fix.theme ?? {}) };
  const vars = {
    bg: t.bg,
    surface: t.surface,
    'surface-2': t.surface2,
    text: t.text,
    muted: t.muted,
    border: t.border,
    accent: t.accent,
    'accent-text': t.accentText,
    'accent-soft': soft(t.accent, t.dark ? 18 : 12, t.surface),
    success: t.success,
    'success-soft': soft(t.success, t.dark ? 18 : 12, t.surface),
    warning: t.warning,
    'warning-soft': soft(t.warning, t.dark ? 18 : 12, t.surface),
    danger: t.danger,
    'danger-soft': soft(t.danger, t.dark ? 18 : 10, t.surface),
    points: t.points,
    'card-bg': t.cardBg,
    'card-text': t.cardText,
    'card-border': t.cardBorder,
    'card-radius': t.cardRadius,
    'card-shadow': t.cardShadow,
    'icon-bg': t.iconBg === 'transparent' ? t.surface2 : t.iconBg,
    'icon-radius': t.iconRadius,
    'btn-bg': t.btnBg,
    'btn-text': t.btnText,
    'btn-border': t.btnBorder,
    'btn-radius': t.btnRadius,
    'btn-shadow': t.btnShadow,
    progress: t.progress,
    'hero-bg': t.heroBg,
    'hero-text': t.heroText,
    'tabbar-bg': t.tabbarBg,
    'tabbar-text': t.tabbarText,
    'tabbar-active': t.tabbarActive,
    'heading-transform': t.headingTransform,
    'heading-spacing': t.headingLetterSpacing,
    font: t.fontBody,
    'font-display': t.fontDisplay,
    radius: t.cardRadius,
    'radius-sm': `min(${t.btnRadius}, 14px)`,
    shadow: t.cardShadow,
  };
  const decl = Object.entries(vars)
    .map(([k, v]) => `  --${k}: ${v};`)
    .join('\n');
  // The page background can be a pattern; colour-only values also feed --bg-color.
  const bgColor = /^#[0-9a-f]{3,8}$/i.test(t.bg) ? t.bg : (t.bg.match(/#[0-9a-f]{6}\b/gi) ?? [t.surface]).at(-1);
  let block = `[data-theme='${t.id}'] {\n${decl}\n  --bg-color: ${bgColor};\n  color-scheme: ${t.dark ? 'dark' : 'light'};\n}`;
  // Light cards inside dark pages need their own text colours.
  const card = fix.card ?? (t.dark && t.cardText !== t.text ? { muted: t.cardText } : null);
  if (card) {
    const cardVars = Object.entries({ text: t.cardText, ...card })
      .map(([k, v]) => `  --${k}: ${v};`)
      .join('\n');
    block += `\n[data-theme='${t.id}'] :is(.task-card, .card, .list, .sheet) {\n${cardVars}\n}`;
  }
  blocks.push(block);
  list.push({
    id: t.id,
    title: t.title.replace(/^\d+\s*·\s*/, ''),
    dark: t.dark,
    preview: { bg: bgColor, card: t.cardBg, accent: t.btnBg, text: t.cardText, font: t.fontDisplay, radius: t.cardRadius, border: t.cardBorder },
    doneLabel: t.doneLabel,
    decorations: t.decorations,
  });
}

const outDir = join(root, 'src/lib/themes');
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'themes.css'), `/* Generated by scripts/gen-themes.mjs from the design mockups. Do not edit by hand. */\n${blocks.join('\n\n')}\n`);
writeFileSync(
  join(outDir, 'themes.ts'),
  `// Generated by scripts/gen-themes.mjs from the design mockups. Do not edit by hand.\n` +
    `export interface ThemeInfo {\n  id: string;\n  title: string;\n  dark: boolean;\n  preview: { bg: string; card: string; accent: string; text: string; font: string; radius: string; border: string };\n  doneLabel: string;\n  decorations: string;\n}\n\n` +
    `export const THEME_LIST: ThemeInfo[] = ${JSON.stringify(list, null, 2)};\n`,
);
console.log(`themes: ${list.length}`);
